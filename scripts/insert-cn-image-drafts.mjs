/**
 * Upload CN diagram SVGs and insert image-based draft questions.
 * node --env-file=.env.local scripts/insert-cn-image-drafts.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { randomUUID } from 'crypto';
import { createClient } from '@supabase/supabase-js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error('Missing Supabase env');
  process.exit(1);
}

const supabase = createClient(url, key);
const bucket = 'mcq-images';
const diagramDir = path.join(__dirname, 'cn-diagrams');

async function uploadSvg(filename) {
  const local = path.join(diagramDir, filename);
  const bytes = fs.readFileSync(local);
  const objectPath = `gate-cn/drafts/${Date.now()}-${filename}`;
  const { error } = await supabase.storage.from(bucket).upload(objectPath, bytes, {
    contentType: 'image/svg+xml',
    upsert: true,
  });
  if (error) throw new Error(`upload ${filename}: ${error.message}`);
  const { data } = supabase.storage.from(bucket).getPublicUrl(objectPath);
  return data.publicUrl;
}

const files = [
  'topology-forwarding.svg',
  'fragmentation-path.svg',
  'sliding-window-link.svg',
  'lan-switch.svg',
];

const urls = {};
for (const f of files) {
  urls[f] = await uploadSvg(f);
  console.log('uploaded', f, '→', urls[f]);
}

