  return nat({
    meta,
    difficulty,
    question: `A $${L}$-bit packet travels $${distKm}\\ \\mathrm{km}$ on a $${R / 1e6}\\ \\mathrm{Mbps}$ link ($v=2\\times 10^{8}\\ \\mathrm{m/s}$). End-to-end delay $T_t+T_p$ in ms (3 decimals) is ____.`,
    answer: totalMs,
    solution: `<p>$T_t=${Tt}\\ \\mathrm{s}$, $T_p=${Tp}\\ \\mathrm{s}$, sum $= ${totalMs}\\ \\mathrm{ms}$.</p>`,
  });
