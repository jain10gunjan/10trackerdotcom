function network(cfg, chapterCfg, difficulty, i) {
  const meta = metaBase(cfg, chapterCfg);
  if (difficulty === 'easy') {
    const masks = [
      { octets: [255, 255, 255, 0], label: '255.255.255.0' },
      { octets: [255, 255, 240, 0], label: '255.255.240.0' },
      { octets: [255, 255, 255, 128], label: '255.255.255.128' },
    ];
    const m = pick(i, masks);
    const hosts = usableHostsFromMask(m.octets);
    const prefix = prefixFromMask(m.octets);
    const hostBits = 32 - prefix;
    return nat({
      meta,
      difficulty,
      question: `An IPv4 subnet uses mask $${m.label}$ ($/${prefix}$). The number of usable host addresses is ____.`,
      answer: hosts,
      solution: `<p><strong>Given:</strong> mask $${m.label}$ which is prefix length $/${prefix}$.</p>
<p><strong>Step 1:</strong> Host bits $= 32 - ${prefix} = ${hostBits}$.</p>
<p><strong>Step 2:</strong> Total addresses in the subnet $= 2^{${hostBits}}$.</p>
<p><strong>Step 3:</strong> Exclude network and broadcast addresses: usable hosts $= 2^{${hostBits}} - 2 = ${hosts}$.</p>
<p><strong>Answer:</strong> $${hosts}$.</p>`,
    });
  }
  if (difficulty === 'medium') {
    const payload = pick(i, [1400, 2000, 3000, 4000]);
    const mtu = pick(i + 2, [576, 820, 1000, 1500]);
    const count = ipv4FragmentCount(payload, mtu, 20);
    return nat({
      meta,
      difficulty,
      question: `An IPv4 datagram carries a $${payload}$-byte payload (IP header $20$ bytes, no options). It must cross a link with MTU $${mtu}$ bytes. Assuming $\\mathrm{DF}=0$ and fragments are formed with maximum legal payload multiples of $8$ bytes, the number of fragments is ____.`,
      answer: count,
      solution: `<p><strong>Given:</strong> payload $= ${payload}$ bytes, IP header $= 20$ bytes, MTU $= ${mtu}$, $\\mathrm{DF}=0$.</p>
<p><strong>Step 1:</strong> Maximum fragment payload must be a multiple of $8$: $\\left\\lfloor \\dfrac{\\mathrm{MTU}-20}{8} \\right\\rfloor \\times 8$.</p>
<p><strong>Step 2:</strong> Number of fragments $= \\left\\lceil \\dfrac{\\text{payload}}{\\text{max fragment payload}} \\right\\rceil = ${count}$.</p>
<p><strong>Answer:</strong> $${count}$ fragments.</p>`,
    });
  }
  return mcq({
    meta,
    difficulty,
    question:
      'When a router performs longest-prefix matching for an IPv4 destination, which entry is preferred?',
    options: [
      'The route with the smallest metric regardless of prefix length',
      'The matching route with the longest prefix length',
      'Always the default route $0.0.0.0/0$',
      'The route learned most recently via ARP',
    ],
    correct: 1,
    solution:
      'Longest-prefix match selects the most specific matching prefix among candidates.',
  });
}

