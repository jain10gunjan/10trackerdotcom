/** Attribution stored in examtracker.year for agent-generated items. */
export const GENERATED_YEAR_LABEL = 'generated by 10tracker.com';

/**
 * GATE bank convention:
 * - solutiontext = written solution (HTML/LaTeX) — always detailed for generated items
 * - solution = GateOverflow URL only (leave empty when there is no GO discussion)
 * - year = attribution label; topic stays the syllabus topic only
 */
function wrapSolution(solution, answerHint) {
  const raw = String(solution || '').trim();
  if (!raw) {
    return `<p><strong>Answer:</strong> ${answerHint}</p>`;
  }
  if (/<\s*p[\s>]|<strong>/i.test(raw)) {
    return raw.includes('<') ? raw : `<p>${raw}</p>`;
  }
  return `<p><strong>Reasoning:</strong> ${raw}</p><p><strong>Answer:</strong> ${answerHint}</p>`;
}

function mcq({
  question,
  options,
  correct,
  solution,
  difficulty,
  meta,
  questionImage = null,
}) {
  const letters = ['A', 'B', 'C', 'D'];
  const letter = letters[correct];
  const row = {
    ...meta,
    question: `<p>${question}</p>`,
    options_A: options[0],
    options_B: options[1],
    options_C: options[2],
    options_D: options[3],
    correct_option: letter,
    solution: '',
    solutiontext: wrapSolution(solution, `Option ${letter}`),
    difficulty,
    year: GENERATED_YEAR_LABEL,
    questionImage,
    _verify: { type: 'mcq', expected: letter },
  };
  return row;
}

function nat({ question, answer, solution, difficulty, meta, questionImage = null }) {
  return {
    ...meta,
    question: `<p>${question}</p>`,
    options_A: '',
    options_B: '',
    options_C: '',
    options_D: '',
    correct_option: String(answer),
    solution: '',
    solutiontext: wrapSolution(solution, `$${answer}$`),
    difficulty,
    year: GENERATED_YEAR_LABEL,
    questionImage,
    _verify: { type: 'nat', expected: String(answer) },
  };
}

