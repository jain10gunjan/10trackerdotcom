function performance(cfg, chapterCfg, difficulty, i) {
  const meta = metaBase(cfg, chapterCfg);
  if (difficulty === 'easy') {
    const bw = pick(i, [1e6, 2e6, 10e6]);
    const delay = pick(i + 1, [10, 20, 5]) / 1000;
    const frame = pick(i + 2, [1000, 2000, 8000]);
    const frames = slidingWindowFrames({
      bandwidthBps: bw,
      propDelaySec: delay,
      frameBits: frame,
    });
    const bwMbps = bw / 1e6;
    const delayMs = delay * 1000;
    const bdp = bw * 2 * delay;
    return nat({
      meta,
      difficulty,
      question: `A link has bandwidth $${bwMbps}\\ \\mathrm{Mbps}$ and one-way propagation delay $${delayMs}\\ \\mathrm{ms}$. Frame size is $${frame}$ bits. For stop-and-wait efficiency approaching $100\\%$ under continuous transmission of back-to-back frames with zero processing delay, the minimum sender window size (in frames) is ____.`,
      answer: frames,
      solution: `<p><strong>Given:</strong> $R = ${bwMbps}\\ \\mathrm{Mbps}$, $T_p = ${delayMs}\\ \\mathrm{ms}$, frame $= ${frame}$ bits.</p>
<p><strong>Step 1:</strong> Round-trip propagation delay $= 2T_p = ${2 * delayMs}\\ \\mathrm{ms}$.</p>
<p><strong>Step 2:</strong> Bandwidth-delay product $\\mathrm{BDP} = R \\cdot 2T_p = ${bdp}$ bits. This is how many bits are “in flight” on the pipe during one RTT.</p>
<p><strong>Step 3:</strong> Number of frames needed to fill the pipe is $W \\ge \\left\\lceil \\dfrac{\\mathrm{BDP}}{\\text{frame size}} \\right\\rceil = ${frames}$.</p>
<p><strong>Answer:</strong> $${frames}$ frames.</p>`,
    });
  }
  if (difficulty === 'medium') {
    return mcq({
      meta,
      difficulty,
      question:
        'Compared with circuit switching, packet switching typically offers which advantage?',
      options: [
        'Guaranteed dedicated bandwidth for the entire session',
        'Better statistical multiplexing of bursty traffic',
        'Zero queueing delay on every hop',
        'No need for routing tables',
      ],
      correct: 1,
      solution:
        'Packet switching shares links among flows and exploits burstiness via statistical multiplexing.',
    });
  }
  const L = pick(i, [1000, 1500, 2000]);
  const R = pick(i + 3, [1e6, 2e6, 8e6]);
  const Tp = pick(i + 5, [10, 15, 25]) / 1000;
  const tt = L / R;
  const util = Number(((tt / (tt + 2 * Tp)) * 100).toFixed(2));
  return nat({
    meta,
    difficulty,
    question: `On a stop-and-wait link, frame length is $${L}$ bits, bandwidth is $${R / 1e6}\\ \\mathrm{Mbps}$, and one-way propagation delay is $${Tp * 1000}\\ \\mathrm{ms}$. Ignore processing and ACK transmission time. Link utilization (in $\\%$, rounded to $2$ decimals) is ____.`,
    answer: util,
    solution: `<p><strong>Given:</strong> frame length $L = ${L}$ bits, $R = ${R / 1e6}\\ \\mathrm{Mbps}$, $T_p = ${Tp * 1000}\\ \\mathrm{ms}$.</p>
<p><strong>Step 1:</strong> Transmission time $T_t = L/R = ${tt}\\ \\mathrm{s}$.</p>
<p><strong>Step 2:</strong> For stop-and-wait with negligible ACK time, cycle time $= T_t + 2T_p = ${tt + 2 * Tp}\\ \\mathrm{s}$.</p>
<p><strong>Step 3:</strong> Utilization $U = \\dfrac{T_t}{T_t + 2T_p} \\times 100\\% = ${util}\\%$.</p>
<p><strong>Answer:</strong> $${util}$.</p>`,
  });
}

